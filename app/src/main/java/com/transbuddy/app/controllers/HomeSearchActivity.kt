    // ─── View binding ──────────────────────────────────────────
    private fun bindViews() {
        drawerLayout    = findViewById(R.id.homeDrawerLayout)
        navigationView  = findViewById(R.id.homeNavigationView)
        toolbar         = findViewById(R.id.homeToolbar)
        etSearch        = findViewById(R.id.etHomeSearch)
        tvSectionTitle  = findViewById(R.id.tvSectionTitle)
        rvGrResults     = findViewById(R.id.rvGrResults)
        rvPickupResults = findViewById(R.id.rvPickupResults)

        etSearch.hint = "Search by GR Number, Name, Department..."
        tvSectionTitle.text = "Student & Faculty Member Search Results"
        rvGrResults.visibility     = View.VISIBLE
        rvPickupResults.visibility = View.GONE
    }

    // ─── Toolbar & Drawer ──────────────────────────────────────
    private fun setupToolbarAndDrawer() {
        setSupportActionBar(toolbar)
        supportActionBar?.setDisplayShowTitleEnabled(false)

        val toggle = ActionBarDrawerToggle(
            this, drawerLayout,
            R.string.navigation_drawer_open,
            R.string.navigation_drawer_close
        )
        drawerLayout.addDrawerListener(toggle)
        toggle.syncState()

        findViewById<android.widget.ImageButton>(R.id.homeBtnMenu).setOnClickListener {
            drawerLayout.openDrawer(GravityCompat.START)
        }

        navigationView.setNavigationItemSelectedListener { menuItem ->
            when (menuItem.itemId) {
                R.id.drawer_home_search -> { /* already here */ }
                R.id.drawer_dashboard -> {
                    startActivity(Intent(this, MainActivity::class.java)); finish()
                }
                R.id.drawer_fuel -> {
                    startActivity(Intent(this, FuelLogsActivity::class.java)); finish()
                }
                R.id.drawer_penalties -> {
                    startActivity(Intent(this, PenaltiesActivity::class.java)); finish()
                }
                R.id.drawer_operations -> {
                    startActivity(Intent(this, OperationsActivity::class.java)); finish()
                }
                R.id.drawer_violations -> {
                    startActivity(Intent(this, ViolationsActivity::class.java)); finish()
                }
            }
            drawerLayout.closeDrawer(GravityCompat.START)
            true
        }
        navigationView.setCheckedItem(R.id.drawer_home_search)
    }

    // ─── RecyclerView Setup ────────────────────────────────────
    private fun setupRecyclerViews() {
        grAdapter = GrSearchAdapter(studentList)
        rvGrResults.apply {
            layoutManager = LinearLayoutManager(this@HomeSearchActivity)
            adapter = grAdapter
            setHasFixedSize(true)
            setItemViewCacheSize(25)
            recycledViewPool.setMaxRecycledViews(0, 30)
            isNestedScrollingEnabled = false
        }

        pickupAdapter = PickupBusAdapter(pickupBusList)
        rvPickupResults.apply {
            layoutManager = LinearLayoutManager(this@HomeSearchActivity)
            adapter = pickupAdapter
            setHasFixedSize(true)
            setItemViewCacheSize(25)
            recycledViewPool.setMaxRecycledViews(0, 30)
            isNestedScrollingEnabled = false
        }
    }

    // ─── Realtime Search Debounced ─────────────────────────────
    private val searchHandler = Handler(Looper.getMainLooper())
    private var searchRunnable: Runnable? = null

    private fun setupSearch() {
        etSearch.addTextChangedListener(object : TextWatcher {
            override fun beforeTextChanged(s: CharSequence?, start: Int, count: Int, after: Int) {}
            override fun onTextChanged(s: CharSequence?, start: Int, before: Int, count: Int) {
                searchRunnable?.let { searchHandler.removeCallbacks(it) }
                searchRunnable = Runnable {
                    val query = s.toString()
                    grAdapter.filter(query, studentList)
                }
                searchHandler.postDelayed(searchRunnable!!, 150)
            }
            override fun afterTextChanged(s: Editable?) {}
        })
    }

    override fun onBackPressed() {
        if (drawerLayout.isDrawerOpen(GravityCompat.START)) {
            drawerLayout.closeDrawer(GravityCompat.START)
        } else {
            super.onBackPressed()
        }
    }
